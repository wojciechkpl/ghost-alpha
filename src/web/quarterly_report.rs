//! Self-contained HTML quarterly report generator.
//!
//! Produces a single `.html` file with embedded CSS and inline tables —
//! no external dependencies, no JavaScript required.

use chrono::Local;
use serde::Serialize;

// ─── Types ───────────────────────────────────────────────────────────────────

#[derive(Debug, Clone, Serialize)]
pub struct QuarterlyReportData {
    pub quarter: String,
    pub portfolio_return_pct: f64,
    pub benchmark_return_pct: f64,
    pub alpha_pct: f64,
    pub allocation_weights: Vec<(String, f64)>,
    pub hhi: f64,
    pub concentration_ticker: String,
    pub concentration_pct: f64,
    pub tax_summary: TaxQuarterSummary,
    pub risk_metrics: RiskMetrics,
    pub rebalancing_actions: Vec<String>,
    pub notes: String,
}

#[derive(Debug, Clone, Serialize)]
pub struct TaxQuarterSummary {
    pub realised_gains_lt: f64,
    pub realised_gains_st: f64,
    pub harvested_losses: f64,
    pub net_tax_liability: f64,
}

#[derive(Debug, Clone, Serialize)]
pub struct RiskMetrics {
    pub portfolio_volatility: f64,
    pub sharpe_ratio: f64,
    pub max_drawdown: f64,
    pub var_95: f64,
}

// ─── Public entry point ──────────────────────────────────────────────────────

/// Generate a self-contained HTML quarterly report.
///
/// Returns an HTML string that can be written directly to a `.html` file.
/// The output is fully self-contained: all CSS is embedded — no internet
/// access required to view the file.
pub fn render_quarterly_report(data: &QuarterlyReportData) -> String {
    let generated_at = Local::now().format("%Y-%m-%d %H:%M:%S").to_string();

    let performance_section = render_performance_section(data);
    let allocation_section = render_allocation_section(&data.allocation_weights);
    let concentration_section = render_concentration_section(data);
    let tax_section = render_tax_section(&data.tax_summary);
    let risk_section = render_risk_section(&data.risk_metrics);
    let rebalancing_section = render_rebalancing_section(&data.rebalancing_actions);
    let notes_section = render_notes_section(&data.notes);

    format!(
        r#"<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>GhostAlpha Quarterly Report — {quarter}</title>
<style>
{css}
</style>
</head>
<body>
<header>
  <h1>Quarterly Portfolio Report</h1>
  <p class="meta">{quarter} &nbsp;|&nbsp; Generated: {generated_at}</p>
</header>
<main>
{performance_section}
{allocation_section}
{concentration_section}
{tax_section}
{risk_section}
{rebalancing_section}
{notes_section}
</main>
<footer>
  <p>Generated by GhostAlpha &mdash; {generated_at}</p>
</footer>
</body>
</html>
"#,
        quarter = data.quarter,
        css = EMBEDDED_CSS,
        generated_at = generated_at,
        performance_section = performance_section,
        allocation_section = allocation_section,
        concentration_section = concentration_section,
        tax_section = tax_section,
        risk_section = risk_section,
        rebalancing_section = rebalancing_section,
        notes_section = notes_section,
    )
}

// ─── Performance section ─────────────────────────────────────────────────────

fn render_performance_section(data: &QuarterlyReportData) -> String {
    let alpha_class = if data.alpha_pct >= 0.0 { "win" } else { "loss" };
    format!(
        r#"<section id="performance">
  <h2>Performance Summary</h2>
  <table>
    <thead>
      <tr>
        <th>Metric</th>
        <th>Value</th>
      </tr>
    </thead>
    <tbody>
      <tr><td>Portfolio Return</td><td>{port:+.2}%</td></tr>
      <tr><td>Benchmark Return</td><td>{bench:+.2}%</td></tr>
      <tr><td class="{alpha_class}">Alpha</td><td class="{alpha_class}">{alpha:+.2}%</td></tr>
    </tbody>
  </table>
</section>"#,
        port = data.portfolio_return_pct,
        bench = data.benchmark_return_pct,
        alpha_class = alpha_class,
        alpha = data.alpha_pct,
    )
}

// ─── Allocation section ──────────────────────────────────────────────────────

fn render_allocation_section(weights: &[(String, f64)]) -> String {
    if weights.is_empty() {
        return r#"<section id="allocation">
  <h2>Allocation</h2>
  <p class="empty">No allocation data available.</p>
</section>"#
            .to_string();
    }

    let rows: String = weights
        .iter()
        .map(|(asset, weight)| {
            format!(
                r#"      <tr><td>{asset}</td><td>{weight:.1}%</td></tr>"#,
                asset = asset,
                weight = weight,
            )
        })
        .collect::<Vec<_>>()
        .join("\n");

    format!(
        r#"<section id="allocation">
  <h2>Allocation</h2>
  <table>
    <thead>
      <tr>
        <th>Asset Class</th>
        <th>Weight %</th>
      </tr>
    </thead>
    <tbody>
{rows}
    </tbody>
  </table>
</section>"#,
        rows = rows,
    )
}

// ─── Concentration section ───────────────────────────────────────────────────

fn render_concentration_section(data: &QuarterlyReportData) -> String {
    format!(
        r#"<section id="concentration">
  <h2>Concentration Metrics</h2>
  <table>
    <thead>
      <tr>
        <th>Metric</th>
        <th>Value</th>
      </tr>
    </thead>
    <tbody>
      <tr><td>HHI (Herfindahl-Hirschman Index)</td><td>{hhi:.4}</td></tr>
      <tr><td>Largest Position</td><td>{ticker} ({pct:.1}%)</td></tr>
    </tbody>
  </table>
</section>"#,
        hhi = data.hhi,
        ticker = data.concentration_ticker,
        pct = data.concentration_pct,
    )
}

// ─── Tax section ─────────────────────────────────────────────────────────────

fn render_tax_section(tax: &TaxQuarterSummary) -> String {
    format!(
        r#"<section id="tax">
  <h2>Tax Summary</h2>
  <table>
    <thead>
      <tr>
        <th>Category</th>
        <th>Amount ($)</th>
      </tr>
    </thead>
    <tbody>
      <tr><td>Realised Gains (Long-Term)</td><td>{lt:.2}</td></tr>
      <tr><td>Realised Gains (Short-Term)</td><td>{st:.2}</td></tr>
      <tr><td>Harvested Losses</td><td>{losses:.2}</td></tr>
      <tr><td>Net Tax Liability</td><td>{net:.2}</td></tr>
    </tbody>
  </table>
</section>"#,
        lt = tax.realised_gains_lt,
        st = tax.realised_gains_st,
        losses = tax.harvested_losses,
        net = tax.net_tax_liability,
    )
}

// ─── Risk metrics section ────────────────────────────────────────────────────

fn render_risk_section(risk: &RiskMetrics) -> String {
    format!(
        r#"<section id="risk">
  <h2>Risk Metrics</h2>
  <table>
    <thead>
      <tr>
        <th>Metric</th>
        <th>Value</th>
      </tr>
    </thead>
    <tbody>
      <tr><td>Portfolio Volatility</td><td>{vol:.2}%</td></tr>
      <tr><td>Sharpe Ratio</td><td>{sharpe:.2}</td></tr>
      <tr><td>Max Drawdown</td><td>{dd:.2}%</td></tr>
      <tr><td>VaR (95%)</td><td>{var:.2}%</td></tr>
    </tbody>
  </table>
</section>"#,
        vol = risk.portfolio_volatility,
        sharpe = risk.sharpe_ratio,
        dd = risk.max_drawdown,
        var = risk.var_95,
    )
}

// ─── Rebalancing actions section ─────────────────────────────────────────────

fn render_rebalancing_section(actions: &[String]) -> String {
    if actions.is_empty() {
        return r#"<section id="rebalancing">
  <h2>Rebalancing Actions</h2>
  <p class="empty">No rebalancing actions this quarter.</p>
</section>"#
            .to_string();
    }

    let items: String = actions
        .iter()
        .map(|a| format!("    <li>{a}</li>", a = a))
        .collect::<Vec<_>>()
        .join("\n");

    format!(
        r#"<section id="rebalancing">
  <h2>Rebalancing Actions</h2>
  <ul>
{items}
  </ul>
</section>"#,
        items = items,
    )
}

// ─── Notes section ───────────────────────────────────────────────────────────

fn render_notes_section(notes: &str) -> String {
    if notes.is_empty() {
        return String::new();
    }
    format!(
        r#"<section id="notes">
  <h2>Notes</h2>
  <p>{notes}</p>
</section>"#,
        notes = notes,
    )
}

