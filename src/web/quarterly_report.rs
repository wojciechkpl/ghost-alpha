// ─── Tests ───────────────────────────────────────────────────────────────────

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_data() -> QuarterlyReportData {
        QuarterlyReportData {
            quarter: "2024 Q3".to_string(),
            portfolio_return_pct: 12.45,
            benchmark_return_pct: 8.30,
            alpha_pct: 4.15,
            allocation_weights: vec![
                ("US Equities".to_string(), 55.0),
                ("Intl Equities".to_string(), 20.0),
                ("Fixed Income".to_string(), 15.0),
                ("Alternatives".to_string(), 10.0),
            ],
            hhi: 0.3450,
            concentration_ticker: "NVDA".to_string(),
            concentration_pct: 18.5,
            tax_summary: TaxQuarterSummary {
                realised_gains_lt: 5200.00,
                realised_gains_st: 1800.00,
                harvested_losses: -3100.00,
                net_tax_liability: 3900.00,
            },
            risk_metrics: RiskMetrics {
                portfolio_volatility: 14.2,
                sharpe_ratio: 1.35,
                max_drawdown: -8.7,
                var_95: -2.1,
            },
            rebalancing_actions: vec![
                "Sold 50 shares AAPL at $192.30".to_string(),
                "Bought 100 shares VTI at $238.10".to_string(),
                "Reduced NVDA from 22% to 18%".to_string(),
            ],
            notes: "Strong quarter driven by AI sector momentum.".to_string(),
        }
    }

    #[test]
    fn test_report_contains_html_structure() {
        let html = render_quarterly_report(&sample_data());
        assert!(html.contains("<html"), "must contain <html> tag");
        assert!(html.contains("<head>"), "must contain <head> tag");
        assert!(html.contains("<body>"), "must contain <body> tag");
        assert!(html.contains("</html>"), "must contain closing </html> tag");
    }

    #[test]
    fn test_report_contains_quarter() {
        let html = render_quarterly_report(&sample_data());
        assert!(html.contains("2024 Q3"), "must contain the quarter string");
    }

    #[test]
    fn test_report_contains_performance_data() {
        let html = render_quarterly_report(&sample_data());
        assert!(html.contains("12.45"), "must contain portfolio return pct");
        assert!(html.contains("8.30"), "must contain benchmark return pct");
        assert!(
            html.contains("Portfolio Return"),
            "must have portfolio return label"
        );
        assert!(
            html.contains("Benchmark Return"),
            "must have benchmark return label"
        );
    }

    #[test]
    fn test_report_contains_allocation_rows() {
        let data = sample_data();
        let html = render_quarterly_report(&data);
        for (asset, _) in &data.allocation_weights {
            assert!(
                html.contains(asset.as_str()),
                "must contain allocation asset: {asset}"
            );
        }
    }

    #[test]
    fn test_report_contains_tax_summary() {
        let html = render_quarterly_report(&sample_data());
        assert!(html.contains("Realised Gains"), "must contain tax heading");
        assert!(
            html.contains("Tax Summary"),
            "must contain Tax Summary section heading"
        );
        assert!(
            html.contains("Harvested Losses"),
            "must contain Harvested Losses row"
        );
        assert!(
            html.contains("Net Tax Liability"),
            "must contain Net Tax Liability row"
        );
    }

    #[test]
    fn test_report_contains_risk_metrics() {
        let html = render_quarterly_report(&sample_data());
        assert!(html.contains("Volatility"), "must contain Volatility label");
        assert!(html.contains("Sharpe"), "must contain Sharpe label");
        assert!(html.contains("Drawdown"), "must contain Drawdown label");
        assert!(html.contains("VaR"), "must contain VaR label");
    }

    #[test]
    fn test_report_contains_rebalancing_actions() {
        let data = sample_data();
        let html = render_quarterly_report(&data);
        for action in &data.rebalancing_actions {
            assert!(
                html.contains(action.as_str()),
                "must contain rebalancing action: {action}"
            );
        }
    }

    #[test]
    fn test_report_not_empty() {
        let html = render_quarterly_report(&sample_data());
        assert!(
            html.len() > 500,
            "report must be > 500 chars, got {}",
            html.len()
        );
    }

    #[test]
    fn test_report_contains_ghostalpha_branding() {
        let html = render_quarterly_report(&sample_data());
        assert!(html.contains("<footer>"), "must have footer element");
        assert!(
            html.contains("GhostAlpha"),
            "footer must contain GhostAlpha branding"
        );
    }
}
