use serde::{Deserialize, Serialize};

/// Structured inputs for generating an Investment Policy Statement.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct IpsInputs {
    pub client_name: String,
    pub date: String,
    pub objectives: String,
    pub risk_tolerance: String,
    pub time_horizon: String,
    pub income_needs: String,
    pub liquidity_needs: String,
    pub tax_situation: String,
    pub legal_constraints: String,
    pub target_allocation: Vec<(String, f64)>,
    pub rebalancing_policy: String,
    pub review_frequency: String,
}

/// Generate a Markdown Investment Policy Statement from structured inputs.
pub fn generate_ips_markdown(inputs: &IpsInputs) -> String {
    let alloc_table: String = inputs
        .target_allocation
        .iter()
        .map(|(asset, w)| format!("| {} | {:.1}% |", asset, w * 100.0))
        .collect::<Vec<_>>()
        .join("\n");

    let client = &inputs.client_name;
    let date = &inputs.date;
    let objectives = &inputs.objectives;
    let risk = &inputs.risk_tolerance;
    let horizon = &inputs.time_horizon;
    let income = &inputs.income_needs;
    let liquidity = &inputs.liquidity_needs;
    let tax = &inputs.tax_situation;
    let legal = &inputs.legal_constraints;
    let rebalance = &inputs.rebalancing_policy;
    let review = &inputs.review_frequency;

    format!(
        r#"# Investment Policy Statement

**Client:** {client}
**Date:** {date}

## 1. Investment Objectives
{objectives}

## 2. Risk Tolerance
{risk}

## 3. Time Horizon
{horizon}

## 4. Income & Liquidity Needs
- **Income:** {income}
- **Liquidity:** {liquidity}

## 5. Tax Considerations
{tax}

## 6. Legal & Regulatory Constraints
{legal}

## 7. Target Asset Allocation

| Asset Class | Weight |
|---|---|
{alloc_table}

## 8. Rebalancing Policy
{rebalance}

## 9. Review Schedule
{review}

---
*Generated by GhostAlpha on {date}*
"#
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_inputs() -> IpsInputs {
        IpsInputs {
            client_name: "Jane Doe".to_string(),
            date: "2026-03-14".to_string(),
            objectives: "Capital appreciation with moderate risk".to_string(),
            risk_tolerance: "Moderate".to_string(),
            time_horizon: "10-15 years".to_string(),
            income_needs: "Minimal current income needed".to_string(),
            liquidity_needs: "Emergency fund of 6 months expenses held separately".to_string(),
            tax_situation: "High marginal bracket, prefer tax-efficient vehicles".to_string(),
            legal_constraints: "No ERISA restrictions".to_string(),
            target_allocation: vec![
                ("US Equities".to_string(), 0.60),
                ("International Equities".to_string(), 0.20),
                ("Fixed Income".to_string(), 0.15),
                ("Cash".to_string(), 0.05),
            ],
            rebalancing_policy: "Rebalance quarterly or when drift exceeds 5%".to_string(),
            review_frequency: "Annually, or upon major life events".to_string(),
        }
    }

    #[test]
    fn test_ips_contains_client_name() {
        let md = generate_ips_markdown(&sample_inputs());
        assert!(md.contains("Jane Doe"), "output must contain client name");
    }

    #[test]
    fn test_ips_contains_all_sections() {
        let md = generate_ips_markdown(&sample_inputs());
        let required = [
            "Investment Objectives",
            "Risk Tolerance",
            "Time Horizon",
            "Income",
            "Liquidity",
            "Tax",
            "Legal",
            "Asset Allocation",
            "Rebalancing",
            "Review",
        ];
        for section in &required {
            assert!(
                md.contains(section),
                "output must contain section: {section}"
            );
        }
    }

    #[test]
    fn test_ips_allocation_table_has_rows() {
        let inputs = sample_inputs();
        let md = generate_ips_markdown(&inputs);
        for (asset, _) in &inputs.target_allocation {
            assert!(
                md.contains(&format!("| {} |", asset)),
                "allocation table must contain row for {asset}"
            );
        }
    }

    #[test]
    fn test_ips_allocation_weights_formatted_as_percent() {
        let md = generate_ips_markdown(&sample_inputs());
        assert!(md.contains("60.0%"), "US Equities should show 60.0%");
        assert!(md.contains("20.0%"), "Intl Equities should show 20.0%");
        assert!(md.contains("15.0%"), "Fixed Income should show 15.0%");
        assert!(md.contains("5.0%"), "Cash should show 5.0%");
    }

    #[test]
    fn test_ips_serde_roundtrip() {
        let inputs = sample_inputs();
        let json = serde_json::to_string(&inputs).expect("serialize");
        let deserialized: IpsInputs = serde_json::from_str(&json).expect("deserialize");
        assert_eq!(deserialized.client_name, inputs.client_name);
        assert_eq!(
            deserialized.target_allocation.len(),
            inputs.target_allocation.len()
        );
        for (a, b) in deserialized
            .target_allocation
            .iter()
            .zip(&inputs.target_allocation)
        {
            assert_eq!(a.0, b.0);
            assert!((a.1 - b.1).abs() < f64::EPSILON);
        }
    }

    #[test]
    fn test_ips_empty_allocation() {
        let mut inputs = sample_inputs();
        inputs.target_allocation.clear();
        let md = generate_ips_markdown(&inputs);
        // Table header must still be present
        assert!(md.contains("| Asset Class | Weight |"));
        assert!(md.contains("|---|---|"));
        // No data rows: the line after the separator should be empty or next section
        let after_sep = md.split("|---|---|").nth(1).expect("separator present");
        let first_line = after_sep.lines().nth(1).unwrap_or("");
        assert!(
            !first_line.starts_with('|'),
            "empty allocation should produce no table data rows"
        );
    }

    #[test]
    fn test_ips_contains_date() {
        let md = generate_ips_markdown(&sample_inputs());
        // Date appears in header
        assert!(md.contains("**Date:** 2026-03-14"));
        // Date appears in footer
        assert!(md.contains("Generated by GhostAlpha on 2026-03-14"));
    }
}
