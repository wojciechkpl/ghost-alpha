//! Interactive setup wizard for Ghost Alpha.
//!
//! The wizard walks the user through configuring all required and optional
//! settings in a single interactive session, then writes:
//!
//! - `config.toml` — non-sensitive settings (api_key references env var)
//! - `.env`        — secrets (API keys, tokens, webhook URLs)
//!
//! Pure generation functions (`build_config_toml`, `build_dot_env`) take plain
//! parameters and return `String` so they can be unit-tested without a TTY.

use std::fs;
use std::path::Path;

use anyhow::{Context, Result};

// ─── Config-file generation (pure, testable) ─────────────────────────────────

/// Parameters collected during the wizard that describe non-sensitive settings.
#[derive(Debug, Clone)]
pub struct WizardConfig {
    /// Indicates whether Telegram was configured (token stored in .env).
    pub has_telegram: bool,
    /// Indicates whether Discord was configured (webhook stored in .env).
    pub has_discord: bool,
    /// Filesystem path to the SQLite database.
    pub db_path: String,
    /// Whether to include a `[sentiment]` section pointing at the model dir.
    pub model_path: Option<String>,
}

/// Render the non-sensitive `config.toml` content as a `String`.
///
/// Secrets are **not** inlined — they are referenced by env-var name so the
/// file is safe to commit (though `.gitignore` excludes it by default).
pub fn build_config_toml(cfg: &WizardConfig) -> String {
    let mut out = String::new();

    out.push_str("# Ghost Alpha configuration\n");
    out.push_str("# Generated by: ghost-alpha setup\n");
    out.push_str("# Secrets live in .env — never commit that file.\n\n");

    out.push_str("[finnhub]\n");
    out.push_str("# API key is read from the GHOST_ALPHA_FINNHUB_API_KEY environment variable.\n");
    out.push_str("api_key = \"FROM_ENV\"\n\n");

    out.push_str("[alerts]\n");
    out.push_str("critical_score_threshold = 90.0\n");
    out.push_str("warning_score_threshold  = 70.0\n");
    out.push_str("info_score_threshold     = 50.0\n\n");

    out.push_str("[storage]\n");
    out.push_str(&format!("db_path = {:?}\n", cfg.db_path));

    if let Some(ref mp) = cfg.model_path {
        out.push('\n');
        out.push_str("[sentiment]\n");
        out.push_str(&format!("model_path = {:?}\n", mp));
    }

    out
}

/// Render the `.env` secrets file content as a `String`.
///
/// Only non-empty secrets are emitted.  The caller is responsible for
/// masking / not logging these values.
pub fn build_dot_env(
    finnhub_api_key: &str,
    telegram_bot_token: Option<&str>,
    telegram_chat_id: Option<&str>,
    discord_webhook_url: Option<&str>,
) -> String {
    let mut out = String::new();

    out.push_str("# Ghost Alpha secrets\n");
    out.push_str("# Generated by: ghost-alpha setup\n");
    out.push_str("# DO NOT commit this file — it is listed in .gitignore.\n\n");

    out.push_str(&format!(
        "GHOST_ALPHA_FINNHUB_API_KEY={}\n",
        finnhub_api_key
    ));

    if let (Some(token), Some(chat_id)) = (telegram_bot_token, telegram_chat_id) {
        if !token.trim().is_empty() && !chat_id.trim().is_empty() {
            out.push_str(&format!("GHOST_ALPHA_TELEGRAM_BOT_TOKEN={}\n", token));
            out.push_str(&format!("GHOST_ALPHA_TELEGRAM_CHAT_ID={}\n", chat_id));
        }
    }

    if let Some(url) = discord_webhook_url {
        if !url.trim().is_empty() {
            out.push_str(&format!("GHOST_ALPHA_DISCORD_WEBHOOK_URL={}\n", url));
        }
    }

    out
}

/// Write `content` to `path`, creating parent directories as needed.
pub fn write_file(path: &str, content: &str) -> Result<()> {
    if let Some(parent) = Path::new(path).parent() {
        if !parent.as_os_str().is_empty() {
            fs::create_dir_all(parent)
                .with_context(|| format!("Failed to create directory for {}", path))?;
        }
    }
    fs::write(path, content).with_context(|| format!("Failed to write {}", path))?;
    Ok(())
}

// ─── Interactive wizard (requires a TTY — not unit-tested) ───────────────────

/// Run the full interactive setup wizard.
///
/// This function drives the terminal prompts via `dialoguer`.  It is **not**
/// unit-tested because it requires an interactive TTY.  The pure generation
/// helpers (`build_config_toml`, `build_dot_env`, `write_file`) are tested
/// separately.
pub async fn run_setup_wizard() -> Result<()> {
    use dialoguer::{theme::ColorfulTheme, Confirm, Input};

    let theme = ColorfulTheme::default();

    println!();
    println!("  Ghost Alpha Setup Wizard");
    println!("  \u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}\u{2550}");
    println!();

    // ── Step 1: Finnhub API key ──────────────────────────────────────────────
    println!("  Step 1/5: Data Provider");
    println!("  \u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}");

    let api_key: String = Input::with_theme(&theme)
        .with_prompt("Finnhub API key (free at https://finnhub.io)")
        .validate_with(|input: &String| {
            if input.trim().is_empty() {
                Err("API key cannot be empty")
            } else {
                Ok(())
            }
        })
        .interact_text()?;

    println!();

    // ── Step 2: Telegram (optional) ─────────────────────────────────────────
    println!("  Step 2/5: Alert Channels — Telegram (optional, press Enter to skip)");
    println!("  \u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}");

    let telegram_token: String = Input::with_theme(&theme)
        .with_prompt("Telegram bot token (from @BotFather, Enter to skip)")
        .allow_empty(true)
        .interact_text()?;

    let (telegram_bot_token, telegram_chat_id) = if telegram_token.trim().is_empty() {
        println!("  (skipped)");
        (None, None)
    } else {
        let chat_id: String = Input::with_theme(&theme)
            .with_prompt("Telegram chat ID")
            .validate_with(|input: &String| {
                if input.trim().is_empty() {
                    Err("Chat ID cannot be empty when bot token is set")
                } else {
                    Ok(())
                }
            })
            .interact_text()?;
        (Some(telegram_token), Some(chat_id))
    };

    println!();

    // ── Step 3: Discord (optional) ──────────────────────────────────────────
    println!("  Step 3/5: Alert Channels — Discord (optional, press Enter to skip)");
    println!("  \u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}");

    let discord_raw: String = Input::with_theme(&theme)
        .with_prompt("Discord webhook URL (Enter to skip)")
        .allow_empty(true)
        .interact_text()?;

    let discord_webhook_url = if discord_raw.trim().is_empty() {
        println!("  (skipped)");
        None
    } else {
        Some(discord_raw)
    };

    println!();

    // ── Step 4: Database path ────────────────────────────────────────────────
    println!("  Step 4/5: Database");
    println!("  \u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}");

    let db_path: String = Input::with_theme(&theme)
        .with_prompt("Database path")
        .default("ghost_alpha.db".to_string())
        .interact_text()?;

    println!();

    // ── Step 5: Sentiment model (optional) ──────────────────────────────────
    println!("  Step 5/5: Sentiment Model (optional)");
    println!("  \u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}\u{2500}");

    let download_sentiment = Confirm::with_theme(&theme)
        .with_prompt("Download FinBERT ONNX model (~400MB)?")
        .default(false)
        .interact()?;

    let model_path = if download_sentiment {
        let mp = "models/finbert".to_string();
        println!("  Model directory will be: {}", mp);
        println!("  Download the FinBERT ONNX model from https://huggingface.co/ProsusAI/finbert");
        println!("  Place model.onnx and tokenizer.json in {}", mp);
        Some(mp)
    } else {
        println!("  (skipped — use --skip-sentiment when screening)");
        None
    };

    println!();

    // ── Write files ──────────────────────────────────────────────────────────
    let wizard_cfg = WizardConfig {
        has_telegram: telegram_bot_token.is_some(),
        has_discord: discord_webhook_url.is_some(),
        db_path: db_path.clone(),
        model_path: model_path.clone(),
    };

    let config_toml_content = build_config_toml(&wizard_cfg);
    let dot_env_content = build_dot_env(
        &api_key,
        telegram_bot_token.as_deref(),
        telegram_chat_id.as_deref(),
        discord_webhook_url.as_deref(),
    );

    write_file("config.toml", &config_toml_content)?;
    write_file(".env", &dot_env_content)?;

    println!("  Config saved to: ./config.toml");
    println!("  Secrets saved to: ./.env");
    println!();
    println!("  Next steps:");
    println!("    ghost-alpha migrate          # Apply database migrations");
    println!("    ghost-alpha screen           # Full S&P 500 screening");
    println!("    ghost-alpha screen --top 10  # Top 10 only");
    println!("    ghost-alpha regime           # Current market regime");
    println!();

    Ok(())
}

// ─── Tests ───────────────────────────────────────────────────────────────────

#[cfg(test)]
mod tests {
    use super::*;

    fn minimal_cfg() -> WizardConfig {
        WizardConfig {
            has_telegram: false,
            has_discord: false,
            db_path: "ghost_alpha.db".to_string(),
            model_path: None,
        }
    }

    // ── build_config_toml ────────────────────────────────────────────────────

    #[test]
    fn config_toml_contains_from_env_placeholder() {
        let content = build_config_toml(&minimal_cfg());
        assert!(
            content.contains("FROM_ENV"),
            "api_key must reference env var"
        );
        assert!(
            !content.contains("actual_key"),
            "api_key must not contain real key"
        );
    }

    #[test]
    fn config_toml_contains_default_db_path() {
        let content = build_config_toml(&minimal_cfg());
        assert!(content.contains("ghost_alpha.db"));
    }

    #[test]
    fn config_toml_contains_alert_thresholds() {
        let content = build_config_toml(&minimal_cfg());
        assert!(content.contains("critical_score_threshold = 90.0"));
        assert!(content.contains("warning_score_threshold  = 70.0"));
        assert!(content.contains("info_score_threshold     = 50.0"));
    }

    #[test]
    fn config_toml_custom_db_path() {
        let cfg = WizardConfig {
            db_path: "/var/lib/ghost-alpha/data.db".to_string(),
            ..minimal_cfg()
        };
        let content = build_config_toml(&cfg);
        assert!(content.contains("/var/lib/ghost-alpha/data.db"));
    }

    #[test]
    fn config_toml_with_model_path_includes_sentiment_section() {
        let cfg = WizardConfig {
            model_path: Some("models/finbert".to_string()),
            ..minimal_cfg()
        };
        let content = build_config_toml(&cfg);
        assert!(
            content.contains("[sentiment]"),
            "must include [sentiment] section"
        );
        assert!(content.contains("models/finbert"));
    }

    #[test]
    fn config_toml_without_model_path_omits_sentiment_section() {
        let content = build_config_toml(&minimal_cfg());
        assert!(
            !content.contains("[sentiment]"),
            "must omit [sentiment] when not configured"
        );
    }

    #[test]
    fn config_toml_is_valid_toml() {
        let cfg = WizardConfig {
            has_telegram: true,
            has_discord: true,
            db_path: "my.db".to_string(),
            model_path: Some("models/finbert".to_string()),
        };
        let content = build_config_toml(&cfg);
        // Replace FROM_ENV placeholder so the TOML is structurally valid and
        // parseable by the config module (which accepts any non-empty string).
        let parseable = content.replace("\"FROM_ENV\"", "\"test-key\"");
        let result: Result<toml::Value, _> = toml::from_str(&parseable);
        assert!(
            result.is_ok(),
            "Generated config.toml must be valid TOML: {:?}",
            result.err()
        );
    }

    // ── build_dot_env ────────────────────────────────────────────────────────

    #[test]
    fn dot_env_contains_finnhub_key() {
        let content = build_dot_env("my-secret-key", None, None, None);
        assert!(content.contains("GHOST_ALPHA_FINNHUB_API_KEY=my-secret-key"));
    }

    #[test]
    fn dot_env_with_telegram_includes_both_vars() {
        let content = build_dot_env("key", Some("bot:TOKEN"), Some("-123456"), None);
        assert!(content.contains("GHOST_ALPHA_TELEGRAM_BOT_TOKEN=bot:TOKEN"));
        assert!(content.contains("GHOST_ALPHA_TELEGRAM_CHAT_ID=-123456"));
    }

    #[test]
    fn dot_env_skips_telegram_when_token_empty() {
        let content = build_dot_env("key", Some(""), Some("-123"), None);
        assert!(!content.contains("GHOST_ALPHA_TELEGRAM_BOT_TOKEN"));
    }

    #[test]
    fn dot_env_skips_telegram_when_chat_id_empty() {
        let content = build_dot_env("key", Some("bot:TOKEN"), Some(""), None);
        assert!(!content.contains("GHOST_ALPHA_TELEGRAM_BOT_TOKEN"));
    }

    #[test]
    fn dot_env_skips_telegram_when_both_none() {
        let content = build_dot_env("key", None, None, None);
        assert!(!content.contains("TELEGRAM"));
    }

    #[test]
    fn dot_env_with_discord_includes_webhook_url() {
        let content = build_dot_env(
            "key",
            None,
            None,
            Some("https://discord.com/api/webhooks/1234/abcd"),
        );
        assert!(content.contains(
            "GHOST_ALPHA_DISCORD_WEBHOOK_URL=https://discord.com/api/webhooks/1234/abcd"
        ));
    }

    #[test]
    fn dot_env_skips_discord_when_url_empty() {
        let content = build_dot_env("key", None, None, Some("  "));
        assert!(!content.contains("DISCORD"));
    }

    #[test]
    fn dot_env_skips_discord_when_none() {
        let content = build_dot_env("key", None, None, None);
        assert!(!content.contains("DISCORD"));
    }

    #[test]
    fn dot_env_all_fields() {
        let content = build_dot_env(
            "finnhub-key",
            Some("bot:12345"),
            Some("-99999"),
            Some("https://discord.com/api/webhooks/x/y"),
        );
        assert!(content.contains("GHOST_ALPHA_FINNHUB_API_KEY=finnhub-key"));
        assert!(content.contains("GHOST_ALPHA_TELEGRAM_BOT_TOKEN=bot:12345"));
        assert!(content.contains("GHOST_ALPHA_TELEGRAM_CHAT_ID=-99999"));
        assert!(content
            .contains("GHOST_ALPHA_DISCORD_WEBHOOK_URL=https://discord.com/api/webhooks/x/y"));
    }

    #[test]
    fn dot_env_format_uses_key_equals_value() {
        // Each non-comment, non-empty line must be KEY=value with no spaces around =
        let content = build_dot_env(
            "mykey",
            Some("bot:t"),
            Some("-1"),
            Some("https://example.com"),
        );
        for line in content.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            assert!(line.contains('='), "line must contain '=': {}", line);
            let parts: Vec<&str> = line.splitn(2, '=').collect();
            assert_eq!(parts.len(), 2, "line must have exactly one '=': {}", line);
            assert!(
                !parts[0].contains(' '),
                "key must not contain spaces: {}",
                line
            );
        }
    }

    // ── write_file ───────────────────────────────────────────────────────────

    #[test]
    fn write_file_creates_file_with_content() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("test.toml");
        let path_str = path.to_str().unwrap();
        write_file(path_str, "hello = \"world\"").unwrap();
        let read_back = std::fs::read_to_string(path_str).unwrap();
        assert_eq!(read_back, "hello = \"world\"");
    }

    #[test]
    fn write_file_creates_parent_dirs() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("nested/dir/config.toml");
        let path_str = path.to_str().unwrap();
        write_file(path_str, "content").unwrap();
        assert!(path.exists());
    }
}
